    const typewriterTranslations = {
        es: ["HELLO!!", "YO SOY"],
        en: ["HELLO!!", "I AM"]
    };

    window.typewriterTranslations = typewriterTranslations;

    let currentLang = localStorage.getItem('lang') || 'es';

    function setLanguage(lang) {
        currentLang = lang;
        window.currentLang = lang;
        localStorage.setItem('lang', lang);
        document.documentElement.lang = lang;

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                if (key === 'footer.copyright') {
                    el.innerHTML = translations[lang][key];
                } else if (key === 'about.desc_1' || key === 'about.desc_2') {
                    el.innerHTML = translations[lang][key];
                } else if (key === 'exp.cotel.tasks' || key === 'exp.civiltronic.tasks' || key === 'exp.metajuego.tasks' || key === 'exp.marpe.tasks' || key === 'exp.wiim.tasks' || key === 'exp.cotel.skills' || key === 'exp.civiltronic.skills' || key === 'exp.metajuego.skills' || key === 'exp.marpe.skills' || key === 'exp.wiim.skills' || key === 'edu.udb1.focus' || key === 'edu.udb2.focus') {
                    el.innerHTML = translations[lang][key].split(';').map(item => `<li>${item}</li>`).join('');
                } else {
                    el.textContent = translations[lang][key];
                }
            }
        });

        if (window.updateTypewriterTexts) {
            window.updateTypewriterTexts(typewriterTranslations[lang]);
        }

        const verMasButton = document.getElementById("verMasButton");
        const moreSection = document.getElementById("additional-sections");

        if (verMasButton && moreSection) {
            const isHidden = moreSection.classList.contains("hidden");
            const t = translations[lang] || {};

            verMasButton.textContent = isHidden
                ? (t['about.ver_mas'] || 'Ver más sobre mi')
                : (t['about.ver_menos'] || 'Ver menos sobre mi');
        }

        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.dataset.lang === lang);
        });
    }

    window.setLanguage = setLanguage;

    window.i18n = { translations, currentLang, setLanguage };

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            setLanguage(btn.dataset.lang);
        });
    });

    document.addEventListener('click', (e) => {
        const btn = e.target.closest('.lang-btn');
        if (!btn) return;
        const lang = btn.dataset.lang;
        if (lang && (lang === 'es' || lang === 'en')) {
            setLanguage(lang);
        }
    });

    setLanguage(currentLang);

    if (window.updateTypewriterTexts) {
        window.updateTypewriterTexts(typewriterTranslations[currentLang]);
    }
